import { sierraChartFills, type SierraAccount } from './sierra-account';
type Hit = { x: number; y: number; w: number; h: number; text: string };
/** Sierra uses solid levels and diamond fills; engine uses dashed levels and triangles. */
export function drawSierraOverlay(ctx: CanvasRenderingContext2D, a: SierraAccount | null | undefined,
  o: { t0Ms: number; start: number; end: number; interval: number; tickSize: number; low: number; high: number;
    left: number; right: number; top: number; bottom: number; levels: boolean; x: (t:number)=>number; y: (tick:number)=>number }): Hit[] {
  if (!a?.simulation) return [];
  const hits: Hit[] = [], color = (role: string) => role === 'STOP' ? '#ff5555' : role === 'TP' ? '#55ff55' : '#55ffff';
  ctx.save(); ctx.font = '16px VGA, monospace'; ctx.textBaseline = 'top';
  const labelRows: number[] = [];
  if (o.levels) for (const order of a.orders.filter(order => order.working && order.price > 0)) {
    const tick = order.price / o.tickSize;
    if (tick < o.low || tick > o.high) continue; // All off-screen prices remain in the account table.
    const y = o.y(tick), label = `SC ${order.role === 'ENTRY' ? order.side.toUpperCase() : order.role} #${order.id}`;
    ctx.strokeStyle = color(order.role); ctx.lineWidth = 1; ctx.setLineDash([]);
    ctx.beginPath(); ctx.moveTo(o.left, y); ctx.lineTo(o.right, y); ctx.stroke();
    if (!labelRows.some(v=>Math.abs(v-y)<17)) {
      const width = ctx.measureText(label).width, x = Math.max(o.left, o.right-width-3), ly = Math.min(o.bottom-16, Math.max(o.top,y+2));
      ctx.fillStyle='#000070';ctx.fillRect(x-2,ly,width+4,16);ctx.fillStyle=color(order.role);ctx.fillText(label,x,ly);labelRows.push(y);
    }
    hits.push({x:(o.left+o.right)/2,y,w:o.right-o.left,h:7,text:`SIERRA ${a.account} · ${order.side.toUpperCase()} ${order.type}\nOrder #${order.id} · ${order.status}\nPrice ${order.price.toFixed(2)}${order.price2>0?` · second price ${order.price2.toFixed(2)}`:''}\n${order.quantity-order.filled} remaining / ${order.quantity} total${order.parentId?`\nAttached to #${order.parentId}`:''}\nSierra-reported order. Queue position is not supplied.`});
  }
  const fills = sierraChartFills(a,o.t0Ms,o.start,o.end);
  const groups = new Map<string, typeof fills>();
  for (const fill of fills) {
    const key=`${Math.floor(fill.timeMs/(o.interval/1e6))}:${fill.side}`;
    const g=groups.get(key);if(g)g.push(fill);else groups.set(key,[fill]);
  }
  for (const group of groups.values()) {
    const price = group.reduce((s,f)=>s+f.price,0)/group.length;
    const time = group.reduce((s,f)=>s+f.timeMs,0)/group.length;
    const x = Math.max(o.left+5,Math.min(o.right-5,o.x((time-o.t0Ms)*1e6))), y = o.y(price/o.tickSize);
    ctx.fillStyle=group[0].side==='buy'?'#55ffff':'#ff88ff';ctx.strokeStyle='#ffffff';ctx.lineWidth=1;
    ctx.beginPath();ctx.moveTo(x,y-5);ctx.lineTo(x+5,y);ctx.lineTo(x,y+5);ctx.lineTo(x-5,y);ctx.closePath();ctx.fill();ctx.stroke();
    const label=`SC ${group[0].side==='buy'?'B':'S'}${group.length>1?` ×${group.length}`:''}`;
    if(o.right-o.left>500||groups.size<=4){const lx=Math.max(o.left,Math.min(o.right-ctx.measureText(label).width,x+7)),ly=Math.max(o.top,Math.min(o.bottom-16,y-19));ctx.fillText(label,lx,ly);}
    hits.unshift({x,y,w:18,h:20,text:`SIERRA ${a.account} · ${group[0].side.toUpperCase()}${group.length>1?` · ${group.length} fills (average marker price)`:''}\n`+group.map(f=>`${new Date(f.timeMs).toISOString()}\n${f.quantity} @ ${f.price.toFixed(2)} · order #${f.orderId}`).join('\n')+'\nSierra execution; not generated by the engine strategy.'});
  }
  ctx.restore(); return hits;
}
